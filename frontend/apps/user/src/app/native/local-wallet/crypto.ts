import { Buffer } from './buffer';
import { generateMnemonic, mnemonicToSeed, validateMnemonic } from '@scure/bip39';
import { wordlist } from '@scure/bip39/wordlists/english.js';
import { HDKey } from '@scure/bip32';
import { base58, base58check } from '@scure/base';
import { HDKey as EdHDKey } from 'micro-key-producer/slip10.js';
import { secp256k1 } from '@noble/curves/secp256k1.js';
import { sha256 } from '@noble/hashes/sha2.js';
import { keccak_256 } from '@noble/hashes/sha3.js';
import { bytesToHex, concatBytes } from '@noble/hashes/utils.js';
import { mnemonicValidate, mnemonicToPrivateKey } from '@ton/crypto';
import { WalletContractV4, WalletContractV5R1 } from '@ton/ton';
import { isRecord } from '@dexwallet/api-client';

export type MnemonicScheme = 'bip39' | 'ton';
export type TonVersion = 'v5r1' | 'v4r2';
export type Network = 'ton-mainnet' | 'ton-testnet' | 'base' | 'solana' | 'tron';
export interface WalletMaterial { version: 1; scheme: MnemonicScheme; words: string; tonVersion: TonVersion }
export interface WalletAccount { network: Network; address: string; path: string }
export const DERIVATION = {
  base: "m/44'/60'/0'/0/0", solana: "m/44'/501'/0'/0'", tron: "m/44'/195'/0'/0/0", ton: "m/44'/607'/0'",
} as const;
export class WalletError extends Error {
  constructor(readonly code: string) { super(code); }
}
export function walletErrorCode(error: unknown): string {
  return error instanceof WalletError ? error.code : isRecord(error) && typeof error.code === 'string' ? error.code : 'LOCAL_FAILED';
}
export function normalizeWords(value: string) { return value.normalize('NFKD').trim().toLowerCase().split(/\s+/).join(' '); }
export function createMaterial(): WalletMaterial {
  return { version: 1, scheme: 'bip39', words: generateMnemonic(wordlist, 256), tonVersion: 'v5r1' };
}
export async function importMaterial(words: string, scheme: MnemonicScheme, tonVersion: TonVersion): Promise<WalletMaterial> {
  const material: WalletMaterial = { version: 1, scheme, words: normalizeWords(words), tonVersion };
  const count = material.words.split(' ').length;
  if (material.words.length > 512 || !['v5r1', 'v4r2'].includes(tonVersion) ||
    !(scheme === 'bip39' ? [12, 24].includes(count) && validateMnemonic(material.words, wordlist)
      : scheme === 'ton' && count === 24 && await mnemonicValidate(material.words.split(' ')))) throw new WalletError('LOCAL_INVALID_MNEMONIC');
  return material;
}
export async function parseMaterial(value: string): Promise<WalletMaterial> {
  let data: unknown;
  try { data = JSON.parse(value); } catch { throw new WalletError('LOCAL_INVALID_SECRET'); }
  if (!isRecord(data) || data.version !== 1 || (data.scheme !== 'bip39' && data.scheme !== 'ton') ||
    (data.tonVersion !== 'v5r1' && data.tonVersion !== 'v4r2') || typeof data.words !== 'string') throw new WalletError('LOCAL_INVALID_SECRET');
  return importMaterial(data.words, data.scheme, data.tonVersion);
}
function evmBytes(publicKey: Uint8Array) { return keccak_256(publicKey.subarray(1)).slice(-20); }
function checksumEVM(bytes: Uint8Array) {
  const hex = bytesToHex(bytes), hash = bytesToHex(keccak_256(new TextEncoder().encode(hex)));
  return '0x' + [...hex].map((c, i) => parseInt(hash[i]!, 16) >= 8 ? c.toUpperCase() : c).join('');
}
function tonAccounts(publicKey: Uint8Array, material: WalletMaterial): WalletAccount[] {
  const path = material.scheme === 'bip39' ? DERIVATION.ton : 'ton-native';
  return ([['ton-mainnet', -239], ['ton-testnet', -3]] as const).map(([network, networkGlobalId]) => {
    const wallet = material.tonVersion === 'v5r1'
      ? WalletContractV5R1.create({ publicKey: Buffer.from(publicKey),
        walletId: { networkGlobalId, context: { walletVersion: 'v5r1', workchain: 0, subwalletNumber: 0 } } })
      : WalletContractV4.create({ publicKey: Buffer.from(publicKey), workchain: 0 });
    return { network, path, address: wallet.address.toString({ bounceable: false, urlSafe: true, testOnly: network === 'ton-testnet' }) };
  });
}
// Callers pass material already validated/generated by the functions above.
export async function deriveAccounts(material: WalletMaterial): Promise<WalletAccount[]> {
  if (material.scheme === 'ton') {
    const keys = await mnemonicToPrivateKey(material.words.split(' '));
    try { return tonAccounts(keys.publicKey, material); } finally { keys.secretKey.fill(0); }
  }
  const seed = await mnemonicToSeed(material.words, '');
  const root = HDKey.fromMasterSeed(seed), edRoot = EdHDKey.fromMasterSeed(seed);
  const base = root.derive(DERIVATION.base), tron = root.derive(DERIVATION.tron);
  const solana = edRoot.derive(DERIVATION.solana), ton = edRoot.derive(DERIVATION.ton);
  try {
    if (!base.privateKey || !tron.privateKey) throw new WalletError('LOCAL_DERIVATION_FAILED');
    return [...tonAccounts(ton.publicKeyRaw, material),
      { network: 'base', path: DERIVATION.base, address: checksumEVM(evmBytes(secp256k1.getPublicKey(base.privateKey, false))) },
      { network: 'solana', path: DERIVATION.solana, address: base58.encode(solana.publicKeyRaw) },
      { network: 'tron', path: DERIVATION.tron, address: base58check(sha256).encode(concatBytes(Uint8Array.of(0x41), evmBytes(secp256k1.getPublicKey(tron.privateKey, false)))) },
    ];
  } finally {
    seed.fill(0); root.wipePrivateData(); base.wipePrivateData(); tron.wipePrivateData();
    for (const node of [edRoot, solana, ton]) { node.privateKey.fill(0); node.chainCode.fill(0); }
  }
}
